"""Regenerate app/common_passwords.py from a pinned public list.

    python3 scripts/build_common_passwords.py [downloaded-file]

Pass a file already downloaded from the URL below (with curl, say) where
Python cannot verify HTTPS itself; it is checked against the same SHA-256.

The source is the UK National Cyber Security Centre's 100,000 most-used
passwords from Have I Been Pwned breach data, as published in SecLists (MIT
licence), fetched at a fixed commit and checked against a SHA-256 so the
output is reproducible and a changed upstream file cannot slip in unnoticed.

Only passwords the length rule would otherwise accept (8 to 128 characters)
are kept, since shorter ones are refused anyway, and the first 10,000 of
those in popularity order are written out: well past the 3,000 that OWASP
ASVS level 1 asks for, at about 100 KB. They are stored as a Python module
rather than a data file so the serverless bundle cannot leave them behind.
"""

from __future__ import annotations

import hashlib
import sys
import unicodedata
import urllib.request
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT_ROOT))

from app.security import MAX_PASSWORD_LENGTH, MIN_PASSWORD_LENGTH  # noqa: E402

COMMIT = "1a7bb9127eca9e6ff2fc0301c597fe6e16a0cb56"
URL = (
    "https://raw.githubusercontent.com/danielmiessler/SecLists/"
    f"{COMMIT}/Passwords/Common-Credentials/100k-most-used-passwords-NCSC.txt"
)
SHA256 = "c2e5696882c603b76bb67a47ee970897e5a76fc4c3f5547abe3d0ca340c576e0"
KEEP = 10_000
OUTPUT = PROJECT_ROOT / "app" / "common_passwords.py"


def main(argv: list[str]) -> int:
    if argv:
        raw = Path(argv[0]).read_bytes()
    else:
        with urllib.request.urlopen(URL, timeout=30) as response:
            raw = response.read()
    digest = hashlib.sha256(raw).hexdigest()
    if digest != SHA256:
        print(f"Checksum mismatch: got {digest}, expected {SHA256}.", file=sys.stderr)
        return 1

    kept: list[str] = []
    seen: set[str] = set()
    for line in raw.decode("utf-8").splitlines():
        key = unicodedata.normalize("NFKC", line).casefold()
        if not MIN_PASSWORD_LENGTH <= len(key) <= MAX_PASSWORD_LENGTH or key in seen:
            continue
        seen.add(key)
        kept.append(key)
        if len(kept) == KEEP:
            break

    body = "\n".join(f"    {password!r}," for password in kept)
    OUTPUT.write_text(
        '"""The most common passwords long enough to pass the length rule.\n\n'
        "Generated by scripts/build_common_passwords.py; do not edit by hand.\n"
        f"Source: NCSC 100k most-used passwords (SecLists @ {COMMIT[:12]}),\n"
        "NFKC-normalised and case-folded, most common first.\n"
        '"""\n\n'
        "# fmt: off\n"
        "COMMON_PASSWORDS: frozenset[str] = frozenset((\n"
        f"{body}\n"
        "))\n"
        "# fmt: on\n"
    )
    print(f"Wrote {len(kept)} passwords to {OUTPUT.relative_to(PROJECT_ROOT)}.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
